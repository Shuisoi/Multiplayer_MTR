import type {InjectionKey, Ref} from "vue";
import type {Camera} from "@/domain/camera";

/**
 * 摄像机的注入键。
 *
 * <p>轨道层与节点层都需要把世界坐标投影到屏幕，它们必须用**同一份**摄像机。
 * 用 `provide/inject` 而不是逐层传 prop：少一层中转就少一次"传丢了"的机会——
 * 上一版把比例从视口经父组件传到节点，就在这一跳上丢过一次（节点按过期比例渲染成 0.3px）。</p>
 */
export const CAMERA: InjectionKey<Ref<Camera>> = Symbol("mmtr-camera");

/**
 * 地图标注图标（信号灯 / 道岔菱形）的**统一直径**：8 px。
 *
 * <p>用户 2026-09-15 的规格："就应该做成固定大小的，比如 8px"。</p>
 *
 * <p>为什么是**固定**而不是随缩放：图标是屏幕像素画的地图标注，一屏上有几十盏灯、四十来个道岔，
 * 它们要能"一眼认出在哪、是什么形状"，而不是跟着世界大小变。早先的图标是 20/23 px，
 * 全览站场时它们挤成一片、把轨与区间都遮住；缩放到 8 px 之后密度问题也随之消失
 * （8 px 的标注不会互相盖住）。</p>
 *
 * <p>放在这里而不是各自写死：两个图层必须**同一个尺寸**，否则"灯和道岔一样大"这件事
 * 会随谁改谁而漂移。</p>
 */
export const MARKER_ICON_PX = 8;
